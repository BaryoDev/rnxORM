// Writes dist/index.mjs, a thin ESM wrapper over the CommonJS build.
// There is one copy of the code (dist/index.js), so the metadata registry
// stays a single instance whether a consumer uses import or require.
// The export list is read from the built module, so it cannot drift.
const fs = require('fs');
const path = require('path');

const dist = path.join(__dirname, '..', 'dist');
const cjs = require(path.join(dist, 'index.js'));

const names = Object.keys(cjs)
    .filter((name) => name !== 'default' && name !== '__esModule')
    .sort();

for (const name of names) {
    if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) {
        throw new Error(`Cannot export "${name}" from an ES module wrapper.`);
    }
}

const lines = [
    '// Generated by scripts/build-esm.js. Do not edit.',
    "import cjs from './index.js';",
    '',
    'export default cjs;',
    ...names.map((name) => `export const ${name} = cjs.${name};`),
    '',
];

fs.writeFileSync(path.join(dist, 'index.mjs'), lines.join('\n'));
console.log(`dist/index.mjs: ${names.length} exports`);
